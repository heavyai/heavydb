//
// Buffer Device Address Test
//
TEST_F(VulkanRenderTest, BufferDeviceAddressTest) {
  auto& device = *this->device_contexts_[0];

  // shader
  auto caches = this->gfx_context_->getShaderManager().createCacheVectorFromTemplate(
      {{"RenderTests/bdaTest.comp"}});
  ASSERT_NE(caches.size(), size_t{0});
  ASSERT_NE(caches[0]->getSpirv().size(), size_t{0});

  auto& resource_mgr = device.getResourceManager();

  // material
  auto material = resource_mgr.createMaterial("Test", caches);
  ASSERT_NE(material, nullptr);

  struct PushConstants {
    uint64_t qob;
    uint64_t chunk;
    uint64_t results;
  };

  // pipeline
  PushConstantRange pcr(ShaderStageBits::kCompute, 0, sizeof(PushConstants));
  auto pipeline = resource_mgr.createComputePipeline("Test", *material, {}, {pcr});
  pipeline->create();

  constexpr uint32_t kNumRows = 100;

  uint32_t subgroup_size = device.getLimits().subgroup_size;
  ASSERT_GT(subgroup_size, 0u);

  // create some more directly-host-visible SSBOs for BDA experiments
  // QOB
  static constexpr BufferUsageBits usage_bits =
      BufferUsageBits::kStorageBufferBit | BufferUsageBits::kDeviceAddressBit;
  auto qob = resource_mgr.createHostVisibleBuffer(
      "QOB", {BufferType::kUnspecified, sizeof(uint64_t) * kNumRows, usage_bits});
  ASSERT_NE(qob, nullptr);
  auto const& qob_buffer = qob->getSourceBufferWrapper();
  // chunks
  auto chunk = resource_mgr.createHostVisibleBuffer(
      "Chunk", {BufferType::kUnspecified, sizeof(double) * kNumRows * 2, usage_bits});
  ASSERT_NE(chunk, nullptr);
  auto const& chunk_buffer = chunk->getSourceBufferWrapper();
  // results
  auto results = resource_mgr.createHostVisibleBuffer(
      "Results", {BufferType::kUnspecified, sizeof(double) * kNumRows * 2, usage_bits});
  ASSERT_NE(results, nullptr);
  auto const& results_buffer = results->getSourceBufferWrapper();

  // prepare material for work
  material->updateDescriptorSets();

  // push constant values
  PushConstants push_constants;
  push_constants.qob = qob_buffer.getBuffer().getDeviceAddress();
  push_constants.chunk = chunk_buffer.getBuffer().getDeviceAddress();
  push_constants.results = results_buffer.getBuffer().getDeviceAddress();

  // build the chunk
  {
    double* chunk_ptr{nullptr};
    chunk->map((void**)&chunk_ptr);
    EXPECT_NE(nullptr, chunk_ptr);
    for (uint32_t i = 0; i < kNumRows; i++) {
      uint32_t chunk_idx = i * 2;
      // x and y for this row
      chunk_ptr[chunk_idx] = double(i);
      chunk_ptr[chunk_idx + 1] = -double(i);
    }
    chunk->unmap();
  }

  // build the QOB
  {
    uint64_t* qob_ptr{nullptr};
    qob->map((void**)&qob_ptr);
    EXPECT_NE(nullptr, qob_ptr);
    for (uint32_t i = 0; i < kNumRows; i++) {
      // the actual device address for each x/y pair
      qob_ptr[i] = push_constants.chunk + (i * 2 * sizeof(double));
    }
    qob->unmap();
  }

  // clear the results
  {
    double* results_ptr{nullptr};
    results->map((void**)&results_ptr);
    EXPECT_NE(nullptr, results_ptr);
    memset(results_ptr, 0, sizeof(double) * kNumRows * 2);
    results->unmap();
  }

  // run
  const uint32_t group_count_x = (kNumRows + subgroup_size - 1) / subgroup_size;
  device.getCommandList()
      .setPushConstants(*pipeline,
                        "Push Constants",
                        ShaderStageBits::kCompute,
                        &push_constants,
                        sizeof(PushConstants))
      .dispatchCompute(*pipeline, 0u, group_count_x, 1u, 1u)
      .flush(kTestFlushName);

  // validate the results
  bool results_correct{true};
  {
    double* results_ptr{nullptr};
    results->map((void**)&results_ptr);
    EXPECT_NE(nullptr, results_ptr);
    for (uint32_t i = 0; i < kNumRows; i++) {
      double expected_x = double(i);
      double expected_y = -double(i);
      uint32_t results_idx = i * 2;
      double x = results_ptr[results_idx];
      double y = results_ptr[results_idx + 1];
      if (x != expected_x || y != expected_y) {
        results_correct = false;
        break;
      }
    }
    results->unmap();
  }
  EXPECT_EQ(results_correct, true);

  // destroy resources
  resource_mgr.destroyPipeline(std::move(pipeline));
  resource_mgr.destroyHostVisibleBuffer(std::move(qob));
  resource_mgr.destroyHostVisibleBuffer(std::move(chunk));
  resource_mgr.destroyHostVisibleBuffer(std::move(results));
  material = nullptr;
}

