  builders[0]->setExternalUniformBuffers(
      {"MODEL_MATRICES_UBO_TYPE", "PROJECTION_UBO_TYPE"});

  auto caches = shader_mgr.createCacheVector(std::move(builders), true);
  auto material = resource_mgr.createMaterial("Material", caches);

  material->bindShaderStorageBufferToBlock("INSTANCE_DATA_SSBO", *instances_ssbo);
  material->bindExternalUniformBufferToBlock("PROJECTION_UBO_TYPE", *projection_ubo);
  material->bindExternalUniformBufferToBlock("MODEL_MATRICES_UBO_TYPE",
                                             *model_matrices_ubo);

  auto material_ssbo =
      cook_torrance_materials.createBuffer(resource_mgr, BufferAccessType::kDeviceLocal);
  cook_torrance_materials.bindToMaterial(*material, *material_ssbo);

  lightmgr.bindToMaterial(*material, *light_data_ssbo);

  // RenderPass and Framebuffer
  auto [attachment_mgr, textures] =
      build_attachments(resource_mgr,
                        kRenderWidth,
                        kRenderHeight,
                        {{PixelFormat::kRGBA8, Framebuffer::Attachment::kColor0}});

  auto render_pass = resource_mgr.createRenderPass("RenderPass",
                                                   attachment_mgr.getLayout(),
                                                   gfx::RenderPass::ClearBits::kAll,
                                                   ImageLayout::kUndefined,
                                                   ImageLayout::kAttachment);

  auto framebuffer = resource_mgr.createFramebuffer(
      "Framebuffer", *render_pass, attachment_mgr, kRenderWidth, kRenderHeight, 1);

  // Mesh
  std::vector<std::string> material_attrs = {{"in_position"}, {"in_normal"}};
  auto mesh_data = build_mesh_draw_data(
      resource_mgr, *build_uv_sphere(40, 20, true), "Sphere", material_attrs, *material);

