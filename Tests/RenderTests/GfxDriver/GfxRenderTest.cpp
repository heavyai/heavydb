  auto& device = *this->device_contexts_[0];

  auto& resource_mgr = device.getResourceManager();

  // material
  auto shader_caches =
      this->gfx_context_->getShaderManager().createCacheVectorFromTemplate(
          {{"DriverTests/fullScreenTriangle.vert"},
           {"RenderTests/emptyFramebufferTest.frag"}});
  ASSERT_TRUE(validate_shader_caches(shader_caches));

