  device.getCommandExecutor().setDefaultViewportAndRenderArea(
      0, 0, kRenderWidth, kRenderHeight);

  // Draw lambda
  auto draw_spheres = [&]() {
    device.getCommandList()
        .beginRenderPass(*render_pass, *framebuffer)
        .drawIndexed(*pipeline,
                     *mesh_data.vbo,
                     *mesh_data.ibo,
                     mesh_data.num_indices,
                     0,
                     0,
                     kNumInstances)
        .endRenderPass()
        .flush("Test");
  };

