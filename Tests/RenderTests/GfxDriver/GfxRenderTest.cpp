  float hue_step = 360.0f / kNumInstances;
  float hue = 0.0f;
  scene.iterateMaterialDescs([&](PBRMaterialDescriptor& desc) {
    desc.albedo = HLSAtoRGBA(hue, 0.5f, 1.0f, 1.0f);
    scene.updateMaterialProperties(desc);
    hue += hue_step;
  });
  scene.updateMaterialDataBuffer();

  // Modify point light and update light ssbo
  point_light_desc.color = glm::vec3{0.1f, 0.4f, 0.8f};
  point_light_desc.multiplier = 1.0f;
  point_light_desc.do_decay = false;
  scene.updateLightProperties(point_light_desc);
  scene.updateLightDataBuffer();

  draw_spheres();
  EXPECT_TRUE(this->golden_image_->compare(
      *framebuffer, Framebuffer::Attachment::kColor0, "pbr_scene_test_1"));

  // Cleanup resources
  resource_mgr.destroyFramebuffer(std::move(framebuffer));
  for (auto& texture : textures) {
    resource_mgr.destroyTexture(std::move(texture));
  }
  resource_mgr.destroyRenderPass(std::move(render_pass));
  resource_mgr.destroyPipeline(std::move(pipeline));
  resource_mgr.destroyBuffer(std::move(instances_ssbo));
  resource_mgr.destroyBuffer(std::move(model_matrices_ubo));
  resource_mgr.destroyBuffer(std::move(projection_ubo));
  scene.destroyResources();
  mesh_data.destroyResources(resource_mgr);
