struct QueryRenderManager::RendererStatusJSONWriter {
  static heavyai::JSON getRendererStatusJSON(const QueryRenderManager& render_manager) {
    heavyai::JSON status;
    // always true
    status["enabled"] = true;
    // Vulkan
    status["driver_type"] =
        std::string(render_manager.gfx_context_->getPrimaryDriver().getName());
    // direct geo rendering
    status["direct_point_rendering_enabled"] = render_manager.canUseSlabAddressTable();
    auto const will_use_mesh_shader =
        render_manager.canUseSlabAddressTable() && render_manager.canUseMeshShaders();
    status["direct_multipoint_rendering_enabled"] = will_use_mesh_shader;
    status["direct_linestring_rendering_enabled"] = false;
    status["direct_multilinestring_rendering_enabled"] = false;
    status["direct_polygon_rendering_enabled"] = false;
    status["direct_multipolygon_rendering_enabled"] = false;
    return status;
  }
};

std::string QueryRenderManager::getRendererStatusJSON() const {
  return RendererStatusJSONWriter::getRendererStatusJSON(*this).stringify();
}

bool QueryRenderManager::validateRendererStatusJSON(
    const std::string& other_renderer_status_json) const {
  std::string this_status_json{"INVALID"};
  try {
    // elements to compare for compatibility
    // in the future, this may not necessarily be all of them
    static const std::vector<std::string> elements_to_compare{"enabled", "driver_type"};
    // get JSON doc for this node (may throw)
    auto const this_status_doc = RendererStatusJSONWriter::getRendererStatusJSON(*this);
    this_status_json = this_status_doc.stringify();
    // parse JSON doc from the incoming blob (may throw)
    heavyai::JSON other_status_doc(other_renderer_status_json);
    // compare elements (may throw)
    for (auto const& element : elements_to_compare) {
      if (this_status_doc[element] != other_status_doc[element]) {
        LOG(ERROR) << "Renderer Status mis-match: "
                   << this_status_doc[element].stringify()
                   << " != " << other_status_doc[element].stringify();
        throw std::runtime_error("see above");
      }
    }
    // all good
    return true;
  } catch (std::runtime_error& e) {
    LOG(ERROR) << "Failed to validate Renderer Status (" << e.what() << ")";
    LOG(ERROR) << "This Renderer Status: " << this_status_json;
    LOG(ERROR) << "Other Renderer Status: " << other_renderer_status_json;
  }
  return false;
}

const RenderSession& QueryRenderManager::getOrCreateRenderSession(
    std::shared_ptr<Catalog_Namespace::SessionInfo> session_info,
    const WidgetId widget_id,
    std::string&& vega_json) {
  RENDER_LOG_SCOPE();

  std::lock_guard<std::mutex> render_lock(render_mutex_);

  // create a temporary RenderSessionKey
  RenderSessionKey temp_render_session_key(session_info, widget_id);
  if (!render_session_mgr_->hasRenderSession(temp_render_session_key)) {
    RENDER_LOG() << "Creating RenderSession";

    // lazy init of GlobalRenderContext
    global_context_->init();

    // add new RenderSession (no QRC yet)
    auto const& render_session = render_session_mgr_->addRenderSession(
        session_info, widget_id, std::move(vega_json));

    // create QRC with the actual RenderSessionKey (not the temp one)
    auto ctx = std::make_unique<QueryRendererContext>(
        render_session.getKey(), *global_context_, true);

    // update the new RenderSession with the QRC
    render_session_mgr_->updateQueryRendererContext(render_session.getKey(),
                                                    std::move(ctx));

    // purge - needs to be performed on the command queue
    command_queue_->submit([&] { render_session_mgr_->purgeUnusedRenderSessions(); });

    // and return the new RenderSession
    return render_session;
  }

  // otherwise, get the existing RenderSession from the map
  auto const& render_session =
      render_session_mgr_->getRenderSession(temp_render_session_key);

  // update the Vega JSON and the last render time
  render_session_mgr_->updateVegaJSONAndLastRenderTime(render_session.getKey(),
                                                       std::move(vega_json));

  // purge - needs to be performed on the command queue
  command_queue_->submit([&] { render_session_mgr_->purgeUnusedRenderSessions(); });

  // and return the existing RenderSession
  return render_session;
}

bool QueryRenderManager::hasRenderSession(const RenderSessionKey& render_session_key) {
  std::lock_guard<std::mutex> render_lock(render_mutex_);
  return render_session_mgr_->hasRenderSession(render_session_key);
}

std::string QueryRenderManager::encodePNG(const RenderPixels& pixels,
                                          const int compression_level) {
  RUNTIME_EX_ASSERT((pixels.width > 0) && (pixels.height > 0) && (!pixels.pixels.empty()),
                    "Unable to encode PNG, invalid RenderPixels: width=" +
                        std::to_string(pixels.width) +
                        ", height=" + std::to_string(pixels.height) +
                        ", size=" + std::to_string(pixels.pixels.size()) + ".");

  QueryRenderer::PngData pngdata(
      pixels.width, pixels.height, pixels.pixels, compression_level);
  return std::move(pngdata.acquireString());
}

