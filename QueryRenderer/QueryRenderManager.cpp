void QueryRenderManager::executeVegaParse(
    const RenderSession& render_session,
    std::shared_ptr<RenderQueryExecuteTimer>& render_timer) {
  RENDER_LOG_SCOPE();
  CHECK(render_timer);
  auto clock_begin = timer_start();

  configureRenderInternal(render_session);

  auto render_query_runner = render_session.getRenderContext().getRenderQueryRunner();
  if (render_query_runner) {
    // tell the query runner that we're ready to render. this will unmap any used render
    // query output buffers for rendering
    render_query_runner->notifyQueryExecutionComplete();
  }

  // Note: this time includes query queue time
  render_timer->vega_parse_time_ms =
      timer_stop(clock_begin) - render_timer->getFullExecutionTime();
}

RenderRequestInfo QueryRenderManager::executeRender(
    const RenderSession& render_session,
    const std::shared_ptr<RenderQueryExecuteTimer>& render_timer,
    QueryRenderCB query_render_func) {
  RENDER_LOG_SCOPE() << "widget: " << render_session.getWidgetId();
  CHECK(render_timer);

  auto clock_begin = timer_start();

  auto render_data = query_render_func(render_session.getRenderContext());
  render_session_mgr_->updateLastRenderTime(render_session.getKey());

  // Note: this time includes query queue time
  render_timer->render_time_ms = timer_stop(clock_begin);

  // Update GfxDriver peak memory usage
  if (auto usage = gfx_context_->getPrimaryDriver().getPeakMemoryUsage();
      usage.size > gfx_peak_memory_usage_) {
    gfx_peak_memory_usage_ = usage.size;
    LOG(INFO) << "New peak render memory usage (res-gpu-mem): " << gfx_peak_memory_usage_;
  }

  return {std::move(render_data),
          render_timer->getFullExecutionTime(),
          render_timer->getFullRenderTime()};
}

RenderRequestInfo QueryRenderManager::runRenderRequest(
    const RenderSession& render_session,
    RenderQueryRunnerUqPtr render_query_runner) {
  RENDER_LOG_SCOPE();
  auto render_timer = std::make_shared<RenderQueryExecuteTimer>();
  std::lock_guard<std::mutex> render_lock(render_mutex_);

  RenderRequestInfo rtn;
  command_queue_->submit(
      [&] {
        render_session.getRenderContext().setQueryExecutionParams(
            std::move(render_query_runner), render_timer);
        executeVegaParse(render_session, render_timer);

        auto query_render_cb = [&](auto& ctx) {
          return global_context_->getRenderer().renderToPixels(ctx);
        };

        rtn = executeRender(render_session, render_timer, query_render_cb);
      },
      [&] { render_session.getRenderContext().unsetQueryExecutionParams(); });
  return rtn;
}

std::tuple<int32_t, int64_t, std::string, int16_t> QueryRenderManager::getIdAt(
    const RenderSession& render_session,
    size_t x,
    size_t y,
    size_t pixel_radius) {
  RENDER_LOG_SCOPE();
  std::lock_guard<std::mutex> render_lock(render_mutex_);

  HitInfo hit_info;
  auto& render_context = render_session.getRenderContext();
  command_queue_->submit([&] { hit_info = render_context.getIdAt(x, y, pixel_radius); });

  // since ids go from 0 to numitems-1 and we're storing the ids as uints, we set a 0 in
  // the id buffers for pixels without hit-test data, and all other rowids are offset by 1
  // in the shaders, so we account for that offset here.
  ResultCacheId result_cache_id = hit_info.result_cache_id;
  auto row_id = static_cast<int64_t>(hit_info.row_id) - 1;
  auto data_id = static_cast<int8_t>(hit_info.vega_data_id);
  auto node_index = hit_info.node_index - 1;
  auto vega_table_name = render_context.getVegaDataNameFromIndex(data_id);
  render_session_mgr_->updateLastRenderTime(render_session.getKey());

  return std::make_tuple(result_cache_id, row_id, vega_table_name, node_index);
}

HitTestCacheResults QueryRenderManager::getQueryCacheResults(
    const ResultCacheId cache_id,
    const int64_t rowid_to_unpack/*,
    const ResultSet::GeoReturnType geo_return_type*/) const {
  RENDER_LOG_SCOPE();
  // Since ids go from 0 to numitems-1 and we store the ids as uints, we set a 0 in
  // the id buffers for pixels without hit-test data, and all other rowids are offset by
  // 1 in the shaders. That +1 offset should've been accounted for in
  // QueryRenderManager::getIdAt(). However, in this case, we need to add that offset back
  // because reprocessing the cached result requires the offset to be re-applied.
  // TODO(croot): This is somewhat of a hidden operation, and it'd be better for it to be
  // more explicit somehow, but given the current API, which is to retrieve the whole
  // rowid, and if that rowid is valid, unpack via this call, this is the best place.
  //
  // TODO(croot): a better API would be to have a dedicated hit-test manager class that
  // manages the current per-user rendered id state. This offsetting logic can all be
  // handled there. See: https://jira.omnisci.com/browse/BE-3260
  auto rtn = global_context_->getRenderQueryCacheMap().getQueryCacheResults(
      cache_id, rowid_to_unpack + 1 /*, geo_return_type*/);

  // Reapply the -1 offset now.
  OffsetAllRowIds rowid_offsetter{-1};
  for (auto itr = rtn.hittest_table_info.begin(); itr != rtn.hittest_table_info.end();
       ++itr) {
    rtn.hittest_table_info.modify(itr, rowid_offsetter);
  }

  return rtn;
}

