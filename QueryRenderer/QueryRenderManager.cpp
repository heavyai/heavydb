// Removes all render sessions for a particular session id.
void QueryRenderManager::removeSessionId(const SessionId& session_id) {
  std::lock_guard<std::mutex> render_lock(render_mutex_);
  command_queue_->submit([&] {
    render_session_mgr_->removeSessionId(session_id);
    validateRenderTargetSize();
  });
}

void QueryRenderManager::validateRenderTargetSize() {
  RENDER_LOG_SCOPE();
  uint32_t max_width = 0;
  uint32_t max_height = 0;
  constexpr auto max_idle_time = std::chrono::milliseconds(60000);  // 1 minute
  auto cutoff_time = getCurrentTimeMS() - max_idle_time;
  render_session_mgr_->iterateRenderSessions([&](const RenderSession& render_session) {
    auto const& ctx = render_session.getRenderContext();
    // only consider sessions that have rendered in the last minute
    if (render_session.getLastRenderTime() > cutoff_time) {
      if (ctx.getWidth() > max_width) {
        max_width = ctx.getWidth();
      }
      if (ctx.getHeight() > max_height) {
        max_height = ctx.getHeight();
      }
    }
  });
  auto [required_width, required_height] =
      get_render_target_size_from_render_size(max_width, max_height);
  if ((global_context_->getRenderTargetWidth() > required_width) ||
      (global_context_->getRenderTargetHeight() > required_height)) {
    global_context_->resetRenderTargetSize();
  }
}

gfx::BufferMemoryDescriptor QueryRenderManager::getQueryOutputBufferDescriptor(
    size_t gpu_index) {
  auto& gpu_data = global_context_->getGpuDataFromIndex(gpu_index);

  // TODO(croot): Is the lock necessary here? Or should we lock on a per-gpu basis?
  std::lock_guard<std::mutex> render_lock(buffer_mutex_);

  gfx::BufferMemoryDescriptor rtn;
  auto query_result_buffer = gpu_data.getQueryResultBuffer();
  if (query_result_buffer) {
    command_queue_->submit([&] {
      setCudaContext(gpu_index);
      query_result_buffer->reset();
      gpu_data.clearQueryOutputBuffer();
      rtn = query_result_buffer->getBufferMemoryDescriptor();
    });
  }

  return rtn;
}

void QueryRenderManager::releaseQueryOutputBufferDescriptor(
    size_t gpu_index,
    size_t num_used_bytes,
    const QueryDataLayoutShPtr& vert_layout) {
  auto& gpu_data = global_context_->getGpuDataFromIndex(gpu_index);
  // TODO(croot): Is the lock necessary here? Or should we lock on a per-gpu basis?
  std::lock_guard<std::mutex> render_lock(buffer_mutex_);

  auto query_result_buffer = gpu_data.getQueryResultBuffer();
  if (query_result_buffer) {
    command_queue_->submit([&] {
      setCudaContext(gpu_index);

      if (vert_layout) {
        query_result_buffer->setQueryDataLayout(vert_layout, num_used_bytes);
      } else if (!num_used_bytes) {
        query_result_buffer->deleteAllQueryDataLayouts();
      }
    });
  }
}

void QueryRenderManager::bufferVboData(int8_t* data,
                                       const size_t num_data_bytes,
                                       const size_t vbo_buffer_offset,
                                       const size_t gpu_index) {
  auto& gpu_data = global_context_->getGpuDataFromIndex(gpu_index);
  // TODO(croot): Is the lock necessary here? Or should we lock on a per-gpu basis?
  std::lock_guard<std::mutex> render_lock(buffer_mutex_);

  auto query_result_vbo = gpu_data.getQueryResultBuffer();
  if (query_result_vbo) {
    command_queue_->submit([&] {
      query_result_vbo->updateSubDataWithLayout(
          reinterpret_cast<void*>(data), num_data_bytes, vbo_buffer_offset, nullptr);
    });
  }
}

void QueryRenderManager::setRenderBufferDataLayout(
    const size_t gpu_index,
    const size_t offset_bytes,
    const size_t num_used_bytes,
    const QueryDataLayoutShPtr& vert_layout) {
  auto& gpu_data = global_context_->getGpuDataFromIndex(gpu_index);
  setCudaContext(gpu_index);

  RUNTIME_EX_ASSERT(vert_layout, "A valid data layout is required");

  // TODO(croot): Is the lock necessary here? Or should we lock on a per-gpu basis?
  std::lock_guard<std::mutex> render_lock(buffer_mutex_);

  // TODO(scb): ContextGuard?
  auto query_result_buffer = gpu_data.getQueryResultBuffer();
  if (query_result_buffer) {
    query_result_buffer->setQueryDataLayout(vert_layout, num_used_bytes, offset_bytes);
  }
}

