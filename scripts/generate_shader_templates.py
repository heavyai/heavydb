import json
import os.path
import shutil

# simple log object (logger would be overkill)
class Log:
    def __init__(self, verbose):
        self.verbose = verbose

    def print_verbose(self, s):
        if self.verbose == True:
            print(s)

def write_cpp_content(file, name, internal_name, class_name, language, raw_src, namespace):
    file.write("#include \"AutoGeneratedShaders.h\"\n\n")
    file.write("namespace " + namespace + " {\n\n")
    file.write("namespace ShaderLibraryAutoGenerated {\n\n")
    file.write("static Item {0} = {{\n".format(name))
    file.write("    \"{0}\",\n".format(internal_name))
    file.write("    \"{0}\",\n".format(class_name))
    file.write("    \"{0}\",\n".format(language))
    file.write("    R\"glsl(\n")
    file.write(raw_src)
    file.write(")glsl\"};\n\n")
    file.write("const Item& get_{0}() {{ return {0}; }}\n".format(name))
    file.write("} // namespace ShaderLibraryAutoGenerated\n\n")
    file.write("} // namespace " + namespace + "\n\n")

def process_source_block(block, base_path, output_path, logger, namespace):
    fname = block['filename']

    src_file = open(base_path + os.path.sep + block['file_path'] + os.path.sep + fname, 'r')
    raw_src = src_file.read()
    src_file.close()

    split_fname = os.path.splitext(fname)
    struct_name = "generated_{0}_{1}".format(split_fname[0], block['class'])
    cpp_fname = struct_name + ".cpp"
    logger.print_verbose("creating file: " + cpp_fname)

    cpp_file = open(output_path + os.path.sep + cpp_fname, 'w')
    write_cpp_content(cpp_file, struct_name, block['internal_path'] + block['filename'], block['class'], block['language'], raw_src, namespace)
    cpp_file.close()
    return struct_name

def write_header(path, names, namespace):
    f = open(path + os.path.sep + '/AutoGeneratedShaders.h', 'w')

    f.write("#pragma once\n")
    f.write("#include <functional>\n")
    f.write("#include <string>\n\n")

    f.write("namespace " + namespace + " {\n\n")
    f.write("namespace ShaderLibraryAutoGenerated {\n\n")
    f.write("struct Item {\n")
    f.write("  std::string internal_name;\n")
    f.write("  std::string class_name;\n")
    f.write("  std::string language;\n")
    f.write("  std::string source;\n")
    f.write("};\n\n")

    f.write("void add_all_to_library(std::function<void (const Item&)> library_add_func);\n\n")
    for n in names:
        f.write("const Item& get_{0}();\n".format(n))
    f.write("} // namespace ShaderLibraryAutoGenerated\n\n")
    f.write("} // namespace " + namespace + "\n\n")

    f.close()

def write_adder(path, names, namespace):
    f = open(path + os.path.sep + '/lib_adder.cpp', 'w')

    f.write("#include \"AutoGeneratedShaders.h\"\n\n")
    f.write("namespace " + namespace + " {\n\n")
    f.write("namespace ShaderLibraryAutoGenerated {\n\n")
    f.write("void add_all_to_library(std::function<void (const Item&)> add_func) {\n")
    for n in names:
        f.write("  add_func(get_{struct}());\n".format(struct=n))
    f.write("}\n\n")
    f.write("} // namespace ShaderLibraryAutoGenerated\n\n")
    f.write("} // namespace " + namespace + "\n\n")

    f.close()

def generate_files(json_sources, base_path, output_path, output_names, logger, namespace):
    for source_block in json_sources:
        output_names.append(process_source_block(source_block, base_path, output_path, logger, namespace))

    logger.print_verbose('generated {0} shader template files'.format(len(output_names)))

def get_valid_json_blocks(json_data, language_filter):
    if not 'sources' in json_data:
        print("Could not find 'source' block in manifest")
        exit(1)

    l = []
    for s in json_data['sources']:
        if s['language'] == language_filter:
            if not 'filename' in s:
                print("Could not find 'filename' in source block")
                exit(1)
            if not 'file_path' in s:
                print("Could not find 'file_path' in source block")
                exit(1)
            if not 'internal_path' in s:
                print("Could not find 'internal_path' in source block")
                exit(1)
            if not 'class' in s:
                print("Could not find 'class' in source block")
                exit(1)
            if not 'language' in s:
                print("Could not find 'language' in source block")
            l.append(s)
    return l

if __name__ == "__main__":
    import sys
    import argparse

    #TODO(scb): add support for multiple manifest files
    p = argparse.ArgumentParser()
    p.add_argument('-n', "--namespace", default=None, help="Namespace to use")
    p.add_argument('-m', "--manifest-list", nargs='+', help="JSON manifest files to use")
    p.add_argument('-s', '--source-dir', default=".", type=str, help='Directory with shader files')
    p.add_argument('-o', '--output-dir', default=None, type=str, help='Output directory for generated files')
    p.add_argument('-v', '--verbose', action="store_true", help="Output generated file list and other information")
    p.add_argument("--print-dependencies", action="store_true", help="Output the list of file dependencies for cmake")
    p.add_argument("--print-outputs", action="store_true", help="Output the list of file outputs for cmake")
    args = p.parse_args()

    logger = Log(args.verbose)

    logger.print_verbose('Python version: {0}'.format(sys.version[:3]))

    if not args.output_dir:
        print("Output path required")
        exit(1)
    output_path = args.output_dir

    # If the output directory exists, remove it to make sure we aren't leaving any cruft behind.
    # TODO: if the output folder contains non-generated files, this will clobber them. Need
    # a better way to track this
    if os.path.exists(output_path):
        logger.print_verbose(output_path + " already exists, removing")
        shutil.rmtree(output_path)

    # Create the output folder
    os.makedirs(output_path)

    # Declare lists and sets to fill as manifests are processed
    dependencies = set([])
    outputs = set([])
    output_names = []
    if args.print_outputs:
        outputs = set(
            [os.path.abspath(output_path + os.path.sep + "AutoGeneratedShaders.h")] +
            [os.path.abspath(output_path + os.path.sep + "lib_adder.cpp")]
        )

    if args.namespace == None:
        print("No namespace provided")
        exit(1)
    namespace = args.namespace

    # Process the manifests
    for manifest_file in args.manifest_list:
        f = open(manifest_file, 'r')
        json_data = json.load(f)
        f.close()
        if not 'sources' in json_data:
            print("Could not find 'source' block in manifest")
            exit(1)
        valid_json_blocks = get_valid_json_blocks(json_data, 'glsl')
        if len(valid_json_blocks) == 0:
            print("No shader sources match the language filter")
            exit(1)

        manifest_path = os.path.dirname(manifest_file)

        # Print the list of input file dependencies to stdout. This is used by CMake
        if args.print_dependencies:
            dependencies.add(os.path.abspath(manifest_file))
            for s in valid_json_blocks:
                dependencies.add(os.path.abspath(manifest_path + os.path.sep + s['file_path'] + os.path.sep + s['filename']))

        # Print the list of output files to stdout for CMake
        elif args.print_outputs:
            for s in valid_json_blocks:
                split_fname = os.path.splitext(s['filename'])
                cpp_name = "generated_{0}_{1}.cpp".format(split_fname[0], s['class'])
                outputs.add(os.path.abspath(output_path + os.path.sep + cpp_name))

        else:
            generate_files(valid_json_blocks, manifest_path, output_path, output_names, logger, namespace)

    if args.print_dependencies:
        sys.stdout.write(';'.join(dependencies))
    elif args.print_outputs:
        sys.stdout.write(';'.join(outputs))
    else:
        logger.print_verbose("creating AutoGeneratedShaders.h")
        write_header(output_path, output_names, namespace)
        logger.print_verbose("creating lib_adder.cpp")
        write_adder(output_path, output_names, namespace)

